export const getProgram = (): Command => {
  const program = addImageImport(
    registerFeedbackCommands(
      addMachineAliases(
        createProgram({
          SDK,
          binaryName: 'dedalus',
          version: '0.6.0', // x-release-please-version
          description: 'CLI for Dedalus',
          defaultFormat: 'json',
          defaultErrorFormat: 'json',
          clientOptions,
          // Feedback owns a positional message and attachment selection instead of generated flags.
          commands: commands.filter(
            (definition: CliCommandDefinition) => definition.resourcePath[0] !== 'feedback',
          ),
          groups,
          completions,
          auth,
        }),
        clientOptions,
        { auth },
      ),
      clientOptions,
      auth,
    ),
    clientOptions,
    auth,
  );
  addUpgradeCommands(program, 'dedalus', '0.6.0'); // x-release-please-version
  return program;
};
